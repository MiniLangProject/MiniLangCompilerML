"""Generate the explicit cache-interface visitor from the parser's AST schema.

The native language has no reflective field enumeration. Keeping this tiny
generator makes a parser field addition visible in both the visitor diff and
the schema regression check. Run with --check in tests; never load cache code.
"""
from pathlib import Path
import re
import sys

ROOT = Path(__file__).resolve().parents[1]
CHILDREN = set("items right left expr callee args target obj index body then_body elifs else_body cond start end_expr iterable cases default_body values range_start range_end methods field_defaults param_defaults lock cleanup defaults".split())


def generate():
    source = (ROOT / "mlc/minilang_parser.ml").read_text(encoding="utf-8")
    nodes = []
    for name, body in re.findall(r"^struct (\w+)\s*\n(.*?)^end struct", source, re.M | re.S):
        fields = re.findall(r"^\s*([A-Za-z_]\w*)\s*,\s*$", body, re.M)
        if "node_kind" in fields:
            nodes.append((name, fields))
    out = '''// Copyright 2026 Nils Kopal. Licensed under the Apache License, Version 2.0.
// Generated by tools/generate_incremental_ast.py; edit its schema rules instead.
//! Deterministic AST declaration projection for incremental invalidation.
package mlc.incremental_ast
import mlc.tools as t
import mlc.data as d
import mlc.cache_codec as codec
import std.string as s

/// Write a complete AST value or an interface with ordinary function bodies omitted.
/// Source positions are excluded: per-module content identities cover debug locations.
/// @param w Mutable primitive encoder.
/// @param node AST value to project.
/// @param interface Whether ordinary function bodies should be excluded.
function write(w, node, interface)
  if w.valid == false then return w end if
  if w.ast_depth >= 128 then w.valid = false; return w end if
  w.ast_depth = w.ast_depth + 1
  writeNode(w, node, interface)
  w.ast_depth = w.ast_depth - 1
  return w
end function

/// Project one node after checking the recursion budget in write().
/// @param w Mutable primitive encoder.
/// @param node AST value to project.
/// @param interface Whether ordinary function bodies should be excluded.
function writeNode(w, node, interface)
  if typeof(node) == "array" then
    codec.write(w, ["array", len(node)])
    for each child in node
      write(w, child, interface)
    end for
    return w
  end if
  kind = t.ast_kind(node)
  if kind == "" then
    codec.write(w, node)
    return w
  end if
  codec.write(w, kind)
  codec.write(w, t.ast_filename(node))
  if kind == "Num" then
    value = t.ast_value(node)
    if typeof(value) == "float" then
      codec.write(w, ["float", d._float_to_f64le(value)])
    else
      codec.write(w, value)
    end if
    return w
  end if
  if kind == "Str" or kind == "Bool" then codec.write(w, t.ast_value(node)); return w end if
  if kind == "Var" then codec.write(w, t.ast_name(node)); return w end if
  if kind == "VoidLit" then return w end if
  if kind == "Bin" then
    write(w, t.ast_left(node), interface)
    codec.write(w, t.ast_op(node))
    write(w, t.ast_right(node), interface)
    return w
  end if
'''
    for name, fields in nodes:
        if name in {"Num", "Str", "Bool", "Var", "VoidLit", "Bin"}:
            continue
        out += f'  if kind == "{name}" then\n'
        for field in fields:
            if field in {"node_kind", "_pos", "_filename"} or field.startswith("_ml_"):
                continue
            if name == "FunctionDef" and field == "body":
                out += '''    // Inline bodies are dependencies of callers; typed and generated
    // candidates are included conservatively before eligibility analysis.
    if interface == false or node.is_inline or typeof(node.return_type) == "string" and node.return_type != "" or s.startsWith(node.name, "__ml_lambda_") then
      write(w, node.body, false)
    end if
'''
            elif field in CHILDREN and not (field == "params"):
                out += f'    write(w, node.{field}, interface)\n'
            else:
                # Extern parameters are AST nodes, whereas function parameters
                # are strings. The recursive visitor handles both safely.
                call = "write" if field == "params" else "codec.write"
                suffix = ", interface" if call == "write" else ""
                out += f'    {call}(w, node.{field}{suffix})\n'
        out += '    return w\n  end if\n'
    out += '''  // A future AST variant must explicitly join the schema before caching.
  w.valid = false
  return w
end function

/// Hash the declaration view without retaining the source AST in the cache.
/// @param program Combined current AST before function bodies are released.
function interfaceKey(program)
  w = codec.writer()
  write(w, program, true)
  return codec.identity(codec.finish(w))
end function
'''
    return re.sub(r"\binterface\b", "headers_only", out)


if __name__ == "__main__":
    destination = ROOT / "mlc/incremental_ast.ml"
    expected = generate()
    if "--check" in sys.argv:
        if not destination.exists() or destination.read_text(encoding="utf-8") != expected:
            raise SystemExit("incremental AST visitor is stale; run tools/generate_incremental_ast.py")
    else:
        destination.write_text(expected, encoding="utf-8", newline="\n")
